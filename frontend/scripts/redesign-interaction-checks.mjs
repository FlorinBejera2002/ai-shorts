import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'

export async function checkRedesignInteractions(page, { clipId, sql, userId }) {
  const m = JSON.parse(await readFile(new URL('../messages/en.json', import.meta.url), 'utf8'))
  const go = path => page.goto(`http://localhost:3000${path}`, {waitUntil:'networkidle'})
  await go('/dashboard/create')
  const tabs = page.getByRole('tab')
  assert.equal(await tabs.count(), 3)
  for (let index=0; index<3; index++) {
    await tabs.nth(index).click()
    assert.equal(await tabs.nth(index).getAttribute('aria-selected'), 'true')
    assert.equal(await page.getByRole('tabpanel').count(), 1)
  }
  await tabs.first().focus()
  await page.keyboard.press('ArrowRight')
  await page.waitForFunction(() => document.querySelectorAll('[role="tab"]')[1]?.getAttribute('aria-selected') === 'true')
  assert.equal(await tabs.nth(1).getAttribute('aria-selected'), 'true')
  const brand = page.getByRole('switch', {name:m.create.brandKit, exact:true})
  const checked = await brand.getAttribute('aria-checked')
  await brand.focus()
  await page.keyboard.press('Space')
  assert.notEqual(await brand.getAttribute('aria-checked'), checked)
  await page.getByRole('button', {name:m.create.advanced, exact:true}).click()
  await page.locator('#create-language').selectOption('ro')
  assert.equal(await page.locator('#create-language').inputValue(), 'ro')
  const slider = page.getByRole('slider', {name:m.create.clipsPerVideo, exact:true})
  await slider.focus()
  const before = Number(await slider.getAttribute('aria-valuenow') ?? await slider.inputValue())
  await page.keyboard.press('ArrowRight')
  const after = Number(await slider.getAttribute('aria-valuenow') ?? await slider.inputValue())
  assert.equal(after, before+1)
  console.log('Create: source tabs/keyboard, brand switch, advanced language and clip-count slider passed')

  await go('/dashboard/script-generator')
  const choices = page.locator('[data-slot="toggle-group-item"]')
  assert.ok(await choices.count() > 10)
  await choices.nth(1).click()
  assert.equal(await choices.nth(1).getAttribute('data-state'), 'on')
  await choices.nth(1).click()
  assert.equal(await choices.nth(1).getAttribute('data-state'), 'on', 'required single choice cannot be cleared')
  assert.equal(await page.getByRole('button',{name:m.scriptGenerator.generateButton,exact:true}).isDisabled(),true)
  assert.equal(await page.getByText(m.scriptGenerator.emptyTitle,{exact:true}).count(),1)
  console.log('Scripts: shadcn selections and empty-input guard passed without an AI request')

  await go(`/dashboard/clips/${clipId}/edit`)
  const help = page.getByRole('button',{name:m.editor.shortcuts,exact:true})
  await help.click()
  const dialog = page.getByRole('dialog')
  await dialog.waitFor()
  assert.equal(await dialog.locator('kbd').count(),10)
  await page.keyboard.press('Escape')
  await dialog.waitFor({state:'hidden'})
  await page.waitForFunction(label=>document.activeElement?.getAttribute('aria-label')===label,m.editor.shortcuts)
  assert.equal(await help.evaluate(el=>el===document.activeElement),true)
  await page.locator('[data-export-trigger]').click()
  await page.getByRole('dialog').waitFor()
  await page.getByRole('button',{name:m.editor.cancel,exact:true}).click()
  await page.getByRole('dialog').waitFor({state:'hidden'})
  await page.waitForFunction(()=>document.activeElement?.hasAttribute('data-export-trigger'))
  assert.equal(await page.locator('[data-export-trigger]').evaluate(el=>el===document.activeElement),true)
  console.log('Editor: shortcuts dialog, Escape/focus return and export cancellation passed; no render requested')

  await go('/dashboard/publish')
  await page.getByRole('button',{name:m.contentCalendar.actions.newPost,exact:true}).first().click()
  await page.getByRole('dialog').waitFor()
  await page.getByLabel(m.contentCalendar.form.titleLabel,{exact:true}).fill('Synthetic redesign calendar test')
  await page.getByLabel(m.contentCalendar.form.statusLabel,{exact:true}).selectOption('draft')
  const [saved] = await Promise.all([
    page.waitForResponse(res=>res.url().endsWith('/api/calendar') && res.request().method()==='POST'),
    page.getByRole('dialog').getByRole('button',{name:m.contentCalendar.actions.create,exact:true}).click()
  ])
  assert.equal(saved.status(),201)
  await page.getByRole('dialog').waitFor({state:'hidden'})
  assert.equal(sql(`SELECT count(*) FROM scheduled_posts WHERE user_id='${userId}' AND title='Synthetic redesign calendar test';`).trim(),'1')
  console.log('Calendar: dialog, draft form and real synthetic persistence passed; no external publication')

  await go('/dashboard/settings')
  await page.locator('#profile-name').fill('Studio Redesign Test')
  const [profileSaved] = await Promise.all([
    page.waitForResponse(res=>res.url().endsWith('/api/user/profile') && res.request().method()==='PATCH'),
    page.getByRole('button',{name:m.settings.saveProfile,exact:true}).click()
  ])
  assert.equal(profileSaved.status(),200)
  assert.equal(sql(`SELECT name FROM users WHERE id='${userId}';`).trim(),'Studio Redesign Test')
  console.log('Settings: shadcn profile form and real synthetic persistence passed')

  await go('/dashboard/brand')
  await page.locator('#font-family').selectOption('Inter')
  const [brandSaved] = await Promise.all([
    page.waitForResponse(res=>res.url().endsWith('/api/user/brand') && ['PUT','POST','PATCH'].includes(res.request().method())),
    page.getByRole('button',{name:m.common.save,exact:true}).click()
  ])
  assert.ok(brandSaved.ok())
  console.log('Brand kit: font selection and real synthetic persistence passed')

  await go('/login')
  await page.getByLabel(m.auth.password,{exact:true}).fill('Synthetic visibility check')
  await page.getByRole('button',{name:m.auth.showPassword,exact:true}).click()
  assert.equal(await page.getByLabel(m.auth.password,{exact:true}).getAttribute('type'),'text')
  await page.getByRole('button',{name:m.auth.hidePassword,exact:true}).click()
  assert.equal(await page.getByLabel(m.auth.password,{exact:true}).getAttribute('type'),'password')
  await go('/reset-password?token=synthetic-token&email=redesign%40example.invalid')
  await page.locator('#password').fill('weak')
  assert.equal(await page.getByRole('button',{name:m.auth.resetButton,exact:true}).isDisabled(),true)
  await page.screenshot({path:'test-results/all-pages/reset-password-validation.png',fullPage:true})
  console.log('Auth: password visibility and reset validation passed without sending email or resetting an account')

  await go('/pricing')
  const faq = page.locator('[data-slot="accordion-trigger"]').first()
  await faq.focus()
  await page.keyboard.press('Enter')
  assert.equal(await faq.getAttribute('aria-expanded'),'true')
  await page.keyboard.press('Enter')
  assert.equal(await faq.getAttribute('aria-expanded'),'false')
  await page.setViewportSize({width:390,height:844})
  const menu = page.getByRole('button',{name:'Open menu',exact:true})
  await menu.click()
  await page.getByRole('dialog').waitFor()
  await page.keyboard.press('Escape')
  await page.getByRole('dialog').waitFor({state:'hidden'})
  await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label')==='Open menu')
  assert.equal(await menu.evaluate(el=>el===document.activeElement),true)
  console.log('Public UI: FAQ keyboard control and mobile Sheet focus return passed')
}
